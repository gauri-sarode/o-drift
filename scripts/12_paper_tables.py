"""Paper tables (LaTeX) and figures (PDF) from the frozen v3 one-shot results.

Reads results/03_test3.json, 03_obd3.json, 04_test3_summary.json, 04_obd3_summary.json,
tuned_v3.json. Writes paper/tables/*.tex and paper/figures/*.pdf. Numbers only; captions are
left to the author (\\todo placeholders).

    PYTHONPATH=src .venv/bin/python scripts/12_paper_tables.py
"""
import json
import re
from pathlib import Path

import matplotlib
import numpy as np

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import matplotlib.ticker  # noqa: E402,F401

ROOT = Path(__file__).resolve().parents[1]
TAB, FIG = ROOT / "paper/tables", ROOT / "paper/figures"
OD, OD1 = "odrift3[0.25]", "odrift[0.0001,5.0,1]"

PRETTY = {  # method family -> short label used in the tables
    "pooled_dr": "Pooled DR", "anchor_dr": "Anchor DR", "recent_dr": "Recent-$k$ DR", "decay_dr": "Decay DR",
    "minvar_dr": "Min-var DR", "liu_reg": "Reg.-DR (Liu)", "transport_dr": "Transport DR", "slope": "SLOPE",
    "magic": "MAGIC", "trecent": "T-recent DR", "tdecay": "T-decay DR", "forecast": "Forecast",
    "timedr": "Time-DR", "tbdecay": "TB-decay DR", "cope": "COPE", "anchor_validated": "Anchor-validated",
    "balanced_dr": "Balanced DR", "monitor_select_dr": "Monitor-select DR",
}


def pretty(m):
    fam = re.match(r"^([a-z_]+)", m).group(1)
    return PRETTY.get(fam, m)


def cell_label(key):
    reg, rest = key.split("@")
    inten, _, mis = rest.partition("#m")
    return reg, float(inten), (float(mis) if mis else 0.5)


def rmse(cell, m):
    return float(np.sqrt(np.mean([[p["err"] ** 2 for p in r[m]] for r in cell["reps"]]))) * 1e3


def bias(cell, m):
    return float(np.mean([[p["err"] for p in r[m]] for r in cell["reps"]])) * 1e3


def sig(ci):  # paired CI excludes 0 -> significance mark
    return "$^{*}$" if (ci[0] > 0 or ci[1] < 0) else ""


def write(name, lines):
    TAB.mkdir(parents=True, exist_ok=True)
    (TAB / name).write_text("\n".join(lines) + "\n")
    print("wrote", (TAB / name).relative_to(ROOT))


def tab_main(data, summ, nov):
    """Main simulator table: accuracy vs best tuned baseline + mechanism checks (COPE, blind grouping)."""
    rows = []
    for key, s in summ.items():
        cell, r = data["cells"][key], nov[key]
        reg, inten, mis = cell_label(key)
        rows.append(f"{reg} & {inten:g} & {mis:g} & {rmse(cell, OD):.1f} & {rmse(cell, OD1):.1f} & "
                    f"{pretty(s['best_baseline'])} & {rmse(cell, s['best_baseline']):.1f} & "
                    f"{s['ratio']:.2f}{sig(s['ci'])} & {s['coverage_hetero']:.2f} & "
                    f"{r['cope_ratio']:.2f}{sig(r['cope_ci'])} & {r['abl_ratio']:.2f}{sig(r['abl_ci'])} & "
                    f"{r['split_od']:.2f} & {r['split_abl']:.2f} \\\\")
    write("tab_main.tex", [
        "% generated by scripts/12_paper_tables.py from results/03_test3.json and 04_test3_summary.json",
        "\\begin{table}[t]\\centering\\scriptsize\\setlength{\\tabcolsep}{2.2pt}",
        "\\caption{One-shot test results on the simulated regimes (300 episodes $\\times$ 4 policies per cell). "
        "RMSE ($\\times10^{-3}$) of \\odrift{}, of its configuration without offset shrinkage (v1) and of the best "
        "tuned baseline in the cell; ratio of \\odrift{} to that baseline and coverage of its nominal 95\\% interval. "
        "Mechanism checks: RMSE ratio of \\odrift{} to tuned COPE and of the blind-grouping ablation (mean-reward "
        "statistic) to \\odrift{}; share of episodes split into more than one segment by the residual monitor (R) "
        "and by the blind statistic (B). $^{*}$: paired 95\\% interval of the RMSE difference excludes 0.}",
        "\\label{tab:main}",
        "\\begin{tabular}{@{}lccrrlrrrrrrr@{}}\\toprule",
        " & & & \\multicolumn{6}{c}{Accuracy} & \\multicolumn{4}{c}{Mechanism checks} \\\\"
        "\\cmidrule(lr){4-9}\\cmidrule(l){10-13}",
        "Reg. & Int. & Mis. & \\odrift{} & v1 & Best baseline & RMSE & Ratio & Cov. & COPE & Blind & R & B \\\\\\midrule",
        *rows, "\\bottomrule\\end{tabular}\\end{table}"])


def tab_novelty(nov):
    rows = []
    for key, r in nov.items():
        reg, inten, mis = cell_label(key)
        rows.append(f"{reg} & {inten:g} & {mis:g} & {r['cope_ratio']:.2f}{sig(r['cope_ci'])} & "
                    f"{r['abl_ratio']:.2f}{sig(r['abl_ci'])} & {r['split_od']:.2f} & {r['split_abl']:.2f} \\\\")
    write("tab_novelty.tex", [
        "% generated by scripts/12_paper_tables.py from results/04_test3_summary.json (novelty rows)",
        "\\begin{table}[t]\\centering\\scriptsize",
        "\\caption{Mechanism checks on the test split. Left: RMSE ratio of \\odrift{} to tuned COPE and of the "
        "blind-grouping ablation (mean-reward statistic) to \\odrift{} ($^{*}$: paired 95\\% interval excludes 0). "
        "Right: share of episodes whose history is split into more than one segment.}",
        "\\label{tab:novelty}",
        "\\begin{tabular}{@{}lccrrrr@{}}\\toprule",
        " & & & \\multicolumn{2}{c}{RMSE ratio} & \\multicolumn{2}{c}{Split rate} \\\\"
        "\\cmidrule(lr){4-5}\\cmidrule(l){6-7}",
        "Regime & Int. & Misspec. & \\odrift{}/COPE & Blind/\\odrift{} & Residual & Blind \\\\\\midrule",
        *rows, "\\bottomrule\\end{tabular}\\end{table}"])


def tab_obd(obd, osumm):
    rows = []
    for key, s in osumm.items():
        cell = obd["cells"][key]
        reg, inten, _ = cell_label(key)
        rows.append(f"{reg} & {inten:g} & {rmse(cell, OD):.1f} & {bias(cell, OD):+.1f} & {rmse(cell, OD1):.1f} & "
                    f"{rmse(cell, 'monitor_select_dr'):.1f} & {pretty(s['best_baseline'])} & "
                    f"{rmse(cell, s['best_baseline']):.1f} & {s['ratio']:.2f}{sig(s['ci'])} \\\\")
    write("tab_obd.tex", [
        "% generated by scripts/12_paper_tables.py from results/03_obd3.json (v3 one-shot, Open Bandit)",
        "\\begin{table}[t]\\centering\\scriptsize",
        "\\caption{One-shot test on semi-synthetic Open Bandit data (200 episodes per cell). RMSE and mean "
        "error (bias) $\\times10^{-3}$; v1 is \\odrift{} without offset shrinkage; monitor-select uses the same "
        "segmentation without reuse. Ratio as in Table~\\ref{tab:main}.}",
        "\\label{tab:obd}",
        "\\begin{tabular}{@{}lcrrrrlrr@{}}\\toprule",
        "Regime & Int. & \\odrift{} & Bias & v1 & Monitor-select & Best tuned baseline & RMSE & Ratio \\\\\\midrule",
        *rows, "\\bottomrule\\end{tabular}\\end{table}"])


CRITERIA = [  # protocol v3 order (go list of 04_analyze --split test3)
    "C1 RMSE $\\le 0.9\\times$ best tuned baseline (CI excludes 0) in $\\ge 2$ reward-drift cells",
    "C2 RMSE $\\le 1.1\\times$ best tuned baseline in S0--S2",
    "C3 split-interval coverage $\\ge 0.93$ in every regime with an anchor",
    "C4 S7: weight on support-deficient windows $\\le 0.05$ in $\\ge 90\\%$ of episodes",
    "C5 no anchor $\\Rightarrow$ not certified in 100\\% of episodes",
    "R1 no reward-drift cell (misspec.\\ 3, Open Bandit) with ratio $> 1.5$",
    "R2 ratio $\\le 1.0$ in at least half of those cells",
    "N1a beats tuned COPE (CI excludes 0) in $\\ge$ half of reward-drift cells",
    "N1b RMSE $\\le 1.1\\times$ COPE in S0--S2",
    "N2a residual monitor false-split rate $\\le 0.05$ in S0--S2",
    "N2b blind grouping worse than \\odrift{} (CI excludes 0) in S1 or S2",
    "N2c blind grouping never $\\le 0.9\\times$ \\odrift{} (CI excludes 0) in a reward-drift cell",
]


def tab_criteria(go):
    assert len(go) == len(CRITERIA), "criteria list out of sync with 04_analyze"
    rows = []
    for label, (raw, ok) in zip(CRITERIA, go):
        detail = re.search(r"\((?:won |got |max )?([^()]*)\)\s*$", raw)
        d = detail.group(1).replace("'", "").replace("_", "\\_") if detail else ""
        d = d.replace("[", "").replace("]", "").replace("@", "@")
        rows.append(f"{label} & {d} & {'pass' if ok else '\\textbf{fail}'} \\\\")
    write("tab_criteria.tex", [
        "% generated by scripts/12_paper_tables.py from results/04_test3_summary.json (pre-registered go/no-go)",
        "\\begin{table}[t]\\centering\\scriptsize",
        "\\caption{Pre-registered criteria (protocol v3) and their one-shot outcome on the test split.}",
        "\\label{tab:criteria}",
        "\\begin{tabular}{@{}p{0.62\\linewidth}p{0.2\\linewidth}l@{}}\\toprule Criterion & Observed & Outcome \\\\\\midrule",
        *rows, "\\bottomrule\\end{tabular}\\end{table}"])


def fig_ratios(summ, nov):
    keys = list(summ)
    y = np.arange(len(keys))[::-1]
    fig, ax = plt.subplots(figsize=(2.4, 3.3))
    ax.axvline(1.0, color="0.6", lw=0.8)
    ax.scatter([summ[k]["ratio"] for k in keys], y, s=14, label="vs best tuned baseline", zorder=3)
    ax.scatter([nov[k]["cope_ratio"] for k in keys if k in nov], [yy for k, yy in zip(keys, y) if k in nov],
               s=14, marker="s", label="vs COPE", zorder=3)
    ax.set_xscale("log")
    ticks = [0.2, 0.5, 1, 2, 3]
    ax.set_xticks(ticks, [f"{t:g}" for t in ticks])
    ax.xaxis.set_minor_formatter(matplotlib.ticker.NullFormatter())
    ax.set_yticks(y, [k.replace("#m3.0", " m3") for k in keys], fontsize=5)
    ax.set_xlabel("RMSE ratio (O-DRIFT / comparator)", fontsize=6)
    ax.tick_params(axis="x", labelsize=6)
    ax.legend(fontsize=5, loc="lower center", bbox_to_anchor=(0.5, 1.0), ncol=2, frameon=False)
    fig.tight_layout()
    FIG.mkdir(parents=True, exist_ok=True)
    fig.savefig(FIG / "fig_ratios.pdf")
    print("wrote", (FIG / "fig_ratios.pdf").relative_to(ROOT))


def fig_splits(nov):
    keys = [k for k, r in nov.items() if r["reg"] in ("S0", "S1", "S2", "S6", "S7")]
    x = np.arange(len(keys))
    fig, ax = plt.subplots(figsize=(2.4, 2.0))
    od_rate = [nov[k]["split_od"] for k in keys]
    ax.bar(x - 0.2, od_rate, 0.4, label="residual monitor")
    ax.plot(x - 0.2, od_rate, "v", ms=3, color="C0")  # zero-height bars stay visible
    ax.bar(x + 0.2, [nov[k]["split_abl"] for k in keys], 0.4, label="mean-reward statistic")
    ax.set_xticks(x, [k.replace("#m3.0", "\nm3").replace("@", "\n") for k in keys], fontsize=5)
    ax.set_ylabel("share of episodes split", fontsize=6)
    ax.set_ylim(0, 1.05)
    ax.tick_params(axis="y", labelsize=5)
    ax.legend(fontsize=5, frameon=False)
    fig.tight_layout()
    fig.savefig(FIG / "fig_splits.pdf")
    print("wrote", (FIG / "fig_splits.pdf").relative_to(ROOT))


def main():
    data = json.loads((ROOT / "results/03_test3.json").read_text())
    obd = json.loads((ROOT / "results/03_obd3.json").read_text())
    s = json.loads((ROOT / "results/04_test3_summary.json").read_text())
    osumm = json.loads((ROOT / "results/04_obd3_summary.json").read_text())["summary"]
    tab_main(data, s["summary"], s["novelty"])
    tab_obd(obd, osumm)
    tab_criteria(s["go"])
    fig_splits(s["novelty"])


if __name__ == "__main__":
    main()
