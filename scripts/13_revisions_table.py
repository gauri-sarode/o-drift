"""Post-hoc revisions on development data (negative results), matched episodes.

v1 (no shrinkage), v3 (offset shrinkage 0.25, the tested version) and v4 (reuse gate, z = 1.96) come
from results/03_dev4.json; v5 (rolling-origin back-test) from results/03_dev5_r13.json, which holds the
first 13 data seeds of every dev environment. All four are compared on those same episodes, with the
best tuned baseline (results/tuned_v4.json) of each cell on the same episodes.

    PYTHONPATH=src .venv/bin/python scripts/13_revisions_table.py
"""
import collections
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
VARIANTS = [("v1", "odrift[0.0001,5.0,1]", "dev4"), ("v3", "odrift3[0.25]", "dev4"),
            ("v4", "odrift4[1.96]", "dev4"), ("v5", "odrift5", "dev5")]


def tuned_baselines(tuned):
    def name(fam, prefix):
        v = tuned[fam]
        return f"{prefix}[{','.join(str(x) for x in v)}]" if isinstance(v, list) else f"{prefix}[{v}]"
    out = ["pooled_dr", "anchor_dr", name("recent", "recent_dr"), name("decay", "decay_dr"), "minvar_dr",
           name("liu", "liu_reg"), "transport_dr"]
    out += [name(f, p) for f, p in (("slope", "slope"), ("magic", "magic"), ("trecent", "trecent"),
                                    ("tdecay", "tdecay"), ("forecast", "forecast"), ("timedr", "timedr"),
                                    ("tbdecay", "tbdecay"), ("cope", "cope"))]
    return out + ["anchor_validated", "balanced_dr", "monitor_select_dr"]


def rmse(reps, m):
    return float(np.sqrt(np.mean([[p["err"] ** 2 for p in r[m]] for r in reps]))) * 1e3


def main():
    d4 = json.loads((ROOT / "results/03_dev4.json").read_text())
    d5 = json.loads((ROOT / "results/03_dev5_r13.json").read_text())
    tuned = json.loads((ROOT / "results/tuned_v4.json").read_text())
    n4, n5 = d4["reps_per_env"], d5["reps_per_env"]
    base = tuned_baselines(tuned)
    rows, summary = [], {}
    for key, c5 in d5["cells"].items():
        c4 = d4["cells"][key]
        idx = [e * n4 + s for e in range(len(d4["env_seeds"])) for s in range(n5)]  # matched episodes
        reps = {"dev4": [c4["reps"][i] for i in idx], "dev5": c5["reps"]}
        assert [c4["env_of_rep"][i] for i in idx] == c5["env_of_rep"]
        b = min((m for m in base if m in reps["dev4"][0]), key=lambda m: rmse(reps["dev4"], m))
        rb = rmse(reps["dev4"], b)
        vals = {v: rmse(reps[src], m) for v, m, src in VARIANTS}
        choice = collections.Counter(r["odrift5"][0]["choice"] for r in c5["reps"])
        summary[key] = dict(best=b, best_rmse=rb, rmse=vals, choice=dict(choice))
        reg, rest = key.split("@")
        inten, _, mis = rest.partition("#m")
        cells = " & ".join(f"{vals[v] / rb:.2f}" for v, _, _ in VARIANTS)
        n = sum(choice.values())
        rows.append(f"{reg} & {float(inten):g} & {float(mis) if mis else 0.5:g} & {rb:.1f} & {cells} & "
                    f"{choice.get('reuse', 0) / n:.2f} & {choice.get('shrink', 0) / n:.2f} & "
                    f"{choice.get('reference', 0) / n:.2f} \\\\")
        print(f"{key:14s} best {b:22s} {rb:5.1f} | " + "  ".join(f"{v} {vals[v]:5.1f}" for v, _, _ in VARIANTS)
              + f" | v5 choice {dict(choice)}")
    (ROOT / "paper/tables/tab_revisions.tex").write_text("\n".join([
        "% generated by scripts/13_revisions_table.py (dev episodes only; post-hoc revisions, never tested)",
        "\\begin{table}[t]\\centering\\scriptsize",
        f"\\caption{{Post-hoc revisions on development data ({n5 * len(d5['env_seeds'])} matched episodes per cell). "
        "RMSE of each version divided by the RMSE of the best tuned baseline (shown, $\\times10^{-3}$). "
        "v1: no offset shrinkage; v3: shrinkage 0.25 (the tested version); v4: reuse gate at $z=1.96$; "
        "v5: rolling-origin back-test, with the share of episodes in which it chose full reuse, shrunk "
        "reuse or no reuse.}",
        "\\label{tab:revisions}",
        "\\begin{tabular}{@{}lccrrrrrrrr@{}}\\toprule",
        " & & & & \\multicolumn{4}{c}{RMSE ratio} & \\multicolumn{3}{c}{v5 choice} \\\\"
        "\\cmidrule(lr){5-8}\\cmidrule(l){9-11}",
        "Reg. & Int. & Mis. & Best & v1 & v3 & v4 & v5 & Reuse & Shrink & None \\\\\\midrule",
        *rows, "\\bottomrule\\end{tabular}\\end{table}"]) + "\n")
    (ROOT / "results/13_revisions_summary.json").write_text(json.dumps(summary, indent=2))
    print("wrote paper/tables/tab_revisions.tex, results/13_revisions_summary.json")


if __name__ == "__main__":
    main()
